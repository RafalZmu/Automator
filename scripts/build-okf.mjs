// Builds the Open Knowledge Format (OKF v0.2) bundle at docs/okf from the
// existing contributor docs. The AGENTS/README/TESTS files stay the source of
// truth; the bundle is a generated, agent-friendly view of them.
//
//   node scripts/build-okf.mjs          write docs/okf
//   node scripts/build-okf.mjs --check  fail if docs/okf is out of date
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const bundleDir = join(root, 'docs', 'okf')
const PRODUCER = 'automator-build-okf/1'

const read = (path) => readFileSync(join(root, path), 'utf8').replace(/\r\n/g, '\n').trimEnd()
const humanize = (slug) => slug.replace(/-/g, ' ').replace(/^./, (c) => c.toUpperCase())

/** Splits a markdown doc into its H1 title and the remaining body. */
function splitTitle(markdown) {
  const match = /^# (.+)\n+/.exec(markdown)
  return match ? { title: match[1].trim(), body: markdown.slice(match[0].length) } : { title: null, body: markdown }
}

/** Demotes headings by `levels` so several documents can nest in one concept. Skips fenced code. */
function demote(markdown, levels) {
  let fenced = false
  return markdown
    .split('\n')
    .map((line) => {
      if (/^\s*(```|~~~)/.test(line)) fenced = !fenced
      return !fenced && /^#{1,6} /.test(line) ? '#'.repeat(Math.min(6, levels) ) + line : line
    })
    .join('\n')
}

function firstParagraph(body) {
  const paragraph = body.split(/\n\s*\n/).find((p) => p.trim() && !p.startsWith('#') && !p.startsWith('|') && !p.trimEnd().endsWith(':')) ?? ''
  const text = paragraph.replace(/\s+/g, ' ').replace(/\[([^\]]+)\]\([^)]*\)/g, '$1').replace(/^[-*] /, '').replace(/\*\*/g, '').trim()
  const sentence = /^(.+?[.!?])(\s|$)/.exec(text)?.[1] ?? text
  return sentence.length > 220 ? `${sentence.slice(0, 217).trimEnd()}...` : sentence
}

const yamlString = (value) => JSON.stringify(value)

function frontmatter({ type, title, description, resource, tags }) {
  return [
    '---',
    `type: ${yamlString(type)}`,
    `title: ${yamlString(title)}`,
    `description: ${yamlString(description)}`,
    `resource: ${yamlString(resource)}`,
    `tags: [${tags.join(', ')}]`,
    `generated: { by: ${PRODUCER} }`,
    '---',
    '',
  ].join('\n')
}

/** Builds a concept from a surface directory (README + AGENTS + optional TESTS). */
function surfaceConcept(kind, slug) {
  const dir = `docs/${kind}/${slug}`
  const readme = splitTitle(read(`${dir}/README.md`))
  const agents = splitTitle(read(`${dir}/AGENTS.md`))
  const testsPath = `${dir}/TESTS.md`
  const tests = existsSync(join(root, testsPath)) ? splitTitle(read(testsPath)) : null
  const isTab = kind === 'tabs'
  const title = readme.title ?? humanize(slug)

  const parts = [
    `# ${title}`,
    '',
    `Source of truth: \`${dir}/\` in the repository. This concept is generated by \`scripts/build-okf.mjs\`; edit the source files, then run \`npm run okf:build\`. Relative links inside the embedded text point at repository paths, not bundle concepts.`,
    '',
    '## Behavior and code map',
    '',
    demote(readme.body, 1),
    '',
    '## Contributor rules',
    '',
    demote(agents.body, 1),
  ]
  if (tests) parts.push('', '## Test cases', '', demote(tests.body, 1))

  return {
    path: `${kind}/${slug}.md`,
    group: isTab ? 'Tabs' : 'Shared sections',
    title,
    description: firstParagraph(readme.body),
    content:
      frontmatter({
        type: isTab ? 'Tab Guide' : 'Section Guide',
        title,
        description: firstParagraph(readme.body),
        resource: `${dir}/`,
        tags: [isTab ? 'tab' : 'section', slug],
      }) + parts.join('\n') + '\n',
  }
}

function documentConcept(path, slug, type, group, tags, descriptionOverride = '') {
  const parsed = splitTitle(read(path))
  const title = parsed.title ?? humanize(slug)
  const description = descriptionOverride || firstParagraph(parsed.body)
  return {
    path: `${group.toLowerCase()}/${slug}.md`,
    group: humanize(group),
    title,
    description,
    content:
      frontmatter({ type, title, description, resource: path, tags }) +
      `# ${title}\n\nSource of truth: \`${path}\`. Generated by \`scripts/build-okf.mjs\`.\n\n${demote(parsed.body, 1)}\n`,
  }
}

const subdirs = (path) =>
  readdirSync(join(root, path), { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort()

const concepts = [
  documentConcept('AGENTS.md', 'workspace-rules', 'Contributor Rules', 'project', ['rules', 'workflow'], 'Repository-wide rules for restarting, verifying, packaging and documenting Automator changes.'),
  ...subdirs('docs/tabs').map((slug) => surfaceConcept('tabs', slug)),
  ...subdirs('docs/sections').map((slug) => surfaceConcept('sections', slug)),
  documentConcept('docs/architecture/bundled-tabs.md', 'bundled-tabs', 'Architecture', 'architecture', ['architecture', 'tabs']),
  documentConcept('docs/architecture/automator-multilayer-graph.md', 'multilayer-graph', 'Architecture', 'architecture', ['architecture', 'runtime']),
]

const GROUP_ORDER = ['Project', 'Tabs', 'Shared sections', 'Architecture']
const DIRECTORY_BLURBS = {
  project: 'Repository-wide rules every contributor and agent must follow.',
  tabs: 'One guide per numbered workspace tab: behavior, code map, contributor rules, test cases.',
  sections: 'Guides for shared surfaces such as Options, the Workspace window and Agent access (MCP).',
  architecture: 'How tabs register and how a request travels through renderer, Electron host and .NET backend.',
}

function indexFor(dirName) {
  const items = concepts.filter((c) => c.path.startsWith(`${dirName}/`))
  return [
    `# ${humanize(dirName)}`,
    '',
    ...items.map((c) => `* [${c.title}](${c.path.slice(dirName.length + 1)}) - ${c.description}`),
    '',
  ].join('\n')
}

function rootIndex() {
  const lines = [
    '---',
    'okf_version: "0.2"',
    '---',
    '',
    '# Automator contributor knowledge',
    '',
    'Open Knowledge Format bundle for agents and people working on Automator. Read the project rules first, then the guide for the surface you are changing. Generated from `AGENTS.md` and `docs/` by `scripts/build-okf.mjs`.',
    '',
  ]
  for (const group of GROUP_ORDER) {
    const items = concepts.filter((c) => c.group === group)
    lines.push(`# ${group}`, '')
    for (const c of items) lines.push(`* [${c.title}](/${c.path}) - ${c.description}`)
    lines.push('')
  }
  lines.push('# Directories', '')
  for (const dirName of Object.keys(DIRECTORY_BLURBS)) lines.push(`* [${humanize(dirName)}](${dirName}/) - ${DIRECTORY_BLURBS[dirName]}`)
  lines.push('')
  return lines.join('\n')
}

const INITIAL_LOG = `# Directory Update Log

## 2026-10-16
* **Creation**: Generated the initial bundle from \`AGENTS.md\` and \`docs/\` with \`scripts/build-okf.mjs\`.
`

export function buildBundle() {
  const files = new Map()
  files.set('index.md', rootIndex())
  for (const dirName of Object.keys(DIRECTORY_BLURBS)) files.set(`${dirName}/index.md`, indexFor(dirName))
  for (const c of concepts) files.set(c.path, c.content)
  return files
}

function readLog() {
  const path = join(bundleDir, 'log.md')
  return existsSync(path) ? readFileSync(path, 'utf8') : INITIAL_LOG
}

function listFiles(dir, base = dir) {
  if (!existsSync(dir)) return []
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory() ? listFiles(join(dir, entry.name), base) : [relative(base, join(dir, entry.name)).replace(/\\/g, '/')],
  )
}

function main() {
  const check = process.argv.includes('--check')
  const files = buildBundle()
  files.set('log.md', readLog())

  if (check) {
    const existing = new Set(listFiles(bundleDir))
    const problems = []
    for (const [path, content] of files) {
      if (!existing.has(path)) problems.push(`missing ${path}`)
      else if (readFileSync(join(bundleDir, path), 'utf8').replace(/\r\n/g, '\n') !== content) problems.push(`stale ${path}`)
      existing.delete(path)
    }
    for (const path of existing) problems.push(`unexpected ${path}`)
    if (problems.length) {
      console.error(`docs/okf is out of date (${problems.join(', ')}). Run: npm run okf:build`)
      process.exit(1)
    }
    console.log(`docs/okf is up to date (${files.size} files).`)
    return
  }

  rmSync(bundleDir, { recursive: true, force: true })
  for (const [path, content] of files) {
    const target = join(bundleDir, path)
    mkdirSync(dirname(target), { recursive: true })
    writeFileSync(target, content)
  }
  console.log(`Wrote ${files.size} files to docs/okf.`)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main()
